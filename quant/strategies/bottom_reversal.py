"""策略：底部反包确认（右侧抄底）——plans/09，从上证 8 个局部底部的量价特征提炼

与 bias_oversold 互补：它是【左侧】（BIAS20 超跌首日就买，买在下跌途中）；
本策略是【右侧】（超跌之后等"中阳反包"确认多头进场才买，买在反弹起点）。

8 个底部事后分析（analyze_bottoms.py，plans/09）提炼出的两条入场共性：
1. 底部都有恐慌极值：6/8 个底部 RSI6 ≤ 25（2023/2026 两个浅底没有——
   它们后来的反弹也最弱（+2.9%/+7.6%），漏掉不可惜）
2. 见底次日有"确认阳线"：6/8 个底部次日涨幅 ≥ +1.6%（中阳反包 = 多头反击）
   → 规则化：前 3 日内 RSI6 曾 ≤ 25，且当日涨幅 ≥ 1%（首日触发）

量能为什么没写进条件（反直觉，重要）：8 个底部里 5 个反弹首日量比 ≤ 1.1x——
恐慌底是"跌缩量、涨也缩量"（卖压衰竭后，很小的买盘就能推高价格），
若照搬教科书要求"放量确认"，会把 2020/2021 两个底误杀掉。
量在本策略里只观察、不判断；长下影同理（5/8 底部出现过，但 2019/2021 没有）。

离场依据（analyze_bottoms.py D 表 + 2026-07-26 用户质疑后的全样本离场对比）：
- 初版 +5%/20日 偏保守（D 表 20 日口径：最大浮盈中位 6.2%）。用户指出 2025-04
  反弹到 +9.5% 才走更划算 → 全样本对比 7 种离场（不是按单一情节定制！）：
  +7%/30~40日 是【平台区】（年化 5.0~5.6%、回撤 -12~-13.5%），50/60 日是【悬崖】
  （回撤 -18%~-31%，且长持仓锁仓错过后续信号——60 日版连 2025-04 这笔都没成交，
  钱还被 1 月的持仓锁着）。故修正为 +7%/30日。
- 反弹峰值日 RSI6 全部 ≥ 71（中位 ~75）——过热规律存在但阈值不稳，只记录不进规则。
- 心得：评价入场要固定离场，评价离场要固定入场；"左/右侧谁优"随离场口径会翻转。

⚠️ 过拟合警告：特征从 8 个"事后挑出来"的底部提炼（看答案编规则），样本外表现
未知；信号稀少（年均约 1-2 次），统计置信度低，收益请按区间理解不按点估计。
"""
from quant import ExitSpec, Strategy
from quant.indicators import cal_rsi
from quant.signals import cross_down


def sig_bottom_reversal(df, rsi_level=25, confirm_ret=0.01):
    """超跌 + 中阳反包确认（右侧进场）。2 个参数，都是整数级（防过拟合）。

    rsi_level:   前 3 日内（含当日）RSI6 曾低于此值 = 恐慌极值出现过
    confirm_ret: 当日涨幅达到此值 = 多头反击的确认阳线（指数 +1% 算中阳）
    """
    oversold = cal_rsi(df["close"], 6) <= rsi_level
    # bool 先转 int8 再 rolling（pandas 对 bool 窗口聚合支持不稳定）；
    # 窗口含当日：确认日当天仍超跌也算（恐慌大阴次日直接 V 起的情形）
    had_oversold = oversold.astype("int8").rolling(3).max().fillna(0).astype(bool)
    confirm = df["close"].pct_change() >= confirm_ret
    return cross_down(had_oversold & confirm)


STRATEGY = Strategy(
    name="bottom_reversal",
    entry_fn=sig_bottom_reversal,
    exit=ExitSpec(take_profit=0.07, max_hold=30),
    note="上证实测：21 笔/胜率 62%/年化 5.1%/回撤 -12.2%（2018-07~2026-07）；"
         "8 底部命中 6。离场经全样本 7 方案对比修正为 +7%/30日（初版 +5%/20日 偏保守）",
)
