# -*- coding: utf-8 -*-
"""组合：三档网格（知乎"波动ETF策略"，计划 19 按翻译流程落地）

原文规则（Knowledge/zhihu/波动ETF策略.md，作者未署名）：
    找一个波动大的指数 ETF（科创板/创业板）；把钱分成 200 份；
    价格 ≤ 三年内最高的 70% 时挂条件单启动；
    档1 每跌 8% 买 8 份 / 每涨 8% 卖 6 份；档2 15% 买 15 卖 12；档3 30% 买 30 卖 20；
    破前高后全清，等下一次条件单。作者的三条纪律：持仓不死、不加杠杆不割肉、长久投资。

机械化后的规则（决策逻辑在 quant/grid.py，参数全部照抄原文）：
    锚点 = 启动日收盘；第 k 档价 = 锚点 × (1−间距)^k；
    每天按收盘所处档位补齐买卖；破前高（收盘）次日全清。

与原文的口径差异（必须知道，不是 bug）：
1. **成交价用次日收盘，不是档位价**——组合引擎只做 T+1 收盘成交（框架没有盘中
   触价能力）。想看盘中限价单口径：analysis/analyze_grid_etf.py，两版差额
   就是"条件单在盘中成交"这件事值多少钱。
2. 标的用**科创50 指数点位**而非 ETF 价：百分比网格对两者等价，指数无拆分/
   跟踪误差干扰；实盘买对应 ETF 每年还有 ~0.5% 管理费+跟踪误差。
3. 成本按双边各 0.1% 计。原文特别强调"佣金是否免5"——本回测**没有**最低 5 元
   佣金这一项，小额分批下它能吃掉大半利润（脚本版有这个敏感性对比）。
4. 原文"有闲钱就转进去"（类定投）不模拟，固定本金。

可执行性（本项目最后一道关）：**支付宝场外基金做不了**——需要券商场内账户 +
条件单。所以这个配方的价值是学习分批建仓的纪律，不是给用户实盘用的。
"""
from quant import Portfolio
from quant.grid import grid_ladder

PORTFOLIO = Portfolio(
    name="grid_3tier",
    holdings={"科创50": "000688"},      # 单标的 + 现金：组合引擎允许留现金、允许分批
    decide_fn=grid_ladder(),             # 参数全用原文默认值（70% 闸门、三档、200 份）
    data_start="20200101",               # 科创50 指数 2019-12-31 发布，从 2020 起干净
    note="日频版实测 2020-01~2026-07：见 run.py 报告；盘中触价版（analyze_grid_etf.py）"
         "同期年化 +6.75%、回撤 -20.6%，两版差额=盘中限价单的价值",
)
